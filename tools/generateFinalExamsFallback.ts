// Regenerates src/extension/finalExamsFallback.ts from the saved raw registrar page, using the same
// parser the extension runs live. Usage:
//   pnpm exec tsx tools/generateFinalExamsFallback.ts src/extension/fixtures/finalExamSchedule-YYYY-MM-DD.html
// finalExamsParse.test.ts asserts the checked-in file equals parse(fixture), so the two can't drift.
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { parseFinalExamSchedule, type PublishedTermExams } from "@/extension/finalExamsParse";
import { parseDetachedDocument } from "@/extension/testing/detachedDocument";

export const FALLBACK_TERMS = ["20263", "20271"];

const fixturePath = process.argv[2];
if (!fixturePath) {
  throw new Error("Pass the raw final-exam-schedule fixture path.");
}
const doc = await parseDetachedDocument(readFileSync(fixturePath, "utf8"));
const terms: PublishedTermExams[] = FALLBACK_TERMS.map((termId) => {
  const result = parseFinalExamSchedule(doc, termId);
  if (!result.ok) {
    throw new Error(result.error);
  }
  if (result.data.unparsedRows.length > 0) {
    throw new Error(`Unparsed rows for ${termId}:\n${result.data.unparsedRows.join("\n")}`);
  }
  return result.data;
});

const source = `// GENERATED by tools/generateFinalExamsFallback.ts from ${basename(fixturePath)}. Do not edit by hand.
// Bundled copy of arr.usc.edu/final-exam-schedule/, used when the live page can't be fetched, can't
// be parsed, or the user declines the arr.usc.edu permission.
import type { PublishedTermExams } from "@/extension/finalExamsParse";

export const FINAL_EXAMS_FALLBACK_SOURCE = ${JSON.stringify(basename(fixturePath))};

export const FINAL_EXAMS_FALLBACK: PublishedTermExams[] = ${JSON.stringify(terms, null, 2)};
`;
writeFileSync("src/extension/finalExamsFallback.ts", source);
console.log(`Wrote ${terms.length} terms.`);
